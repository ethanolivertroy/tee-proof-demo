import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'))
const output = join(root, 'public', 'THIRD_PARTY_NOTICES.txt')

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|$)/i

function licenseText(directory) {
  if (!existsSync(directory)) return null
  const file = readdirSync(directory).find((name) => LICENSE_FILE.test(name))
  return file ? readFileSync(join(directory, file), 'utf8').trim() : null
}

const sections = []
for (const [path, entry] of Object.entries(lock.packages)) {
  if (path === '' || entry.dev) continue
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)
  const manifestPath = join(root, path, 'package.json')
  const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : {}
  const license = typeof manifest.license === 'string' ? manifest.license : entry.license ?? 'UNKNOWN'
  const text = licenseText(join(root, path))
  if (!text && license === 'UNKNOWN') throw new Error(`No license information for ${path}`)
  sections.push(`${name}@${entry.version} (${license})\n\n${text ?? `SPDX: ${license}. No license file is shipped in the package.`}`)
}

const header = 'Third-party notices for the TEE Proof production bundle.\nGenerated by scripts/third-party-notices.mjs from package-lock.json at build time.\n'
writeFileSync(output, [header, ...sections.sort((a, b) => a.localeCompare(b))].join(`\n\n${'='.repeat(72)}\n\n`) + '\n')
console.log(`wrote ${sections.length} notices to public/THIRD_PARTY_NOTICES.txt`)
